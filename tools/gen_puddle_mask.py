#!/usr/bin/env python3
"""Генератор маски калюж для головного меню (assets/ui/puddle_mask.png).

НЕ входить у гру — запускається вручну, коли міняється фонова картина
`assets/ui/menu_background.jpg`. Маска каже шейдеру `puddle_ripples.gdshader`,
де на картині вода: білий = вода (повні брижі), чорний = суходіл (нічого).

Чому не чиста автоматика: «гладке й світліше за оточення» ловить не лише воду,
а й освітлені мішки з піском та дошки настилу — перевірено, покриття виходило
9% екрана з половиною хибних спрацювань. Тому форму водойм задано руками
(PUDDLES, у частках картини — виміряні по сітці), а автооцінка лише уточнює
силует ВСЕРЕДИНІ кожної зони, щоб виступи багна з калюжі не брижились.

Запуск:  python3 tools/gen_puddle_mask.py
Потрібні: Pillow, numpy.
"""
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets/ui/menu_background.jpg")
DST = os.path.join(ROOT, "assets/ui/puddle_mask.png")

## Маска не має бути різкою — вона розмита й керує лише інтенсивністю ефекту,
## тож чверть роздільності картини цілком досить (688x384, ~40 КБ).
DOWNSCALE = 4

## Водойми на картині: (cx, cy, rx, ry) у частках ширини/висоти картини.
## Виміряно по сітці 0.02 (tools/gen_puddle_mask.py --grid у git-історії).
## Горизонт на y≈0.40 — вище нього води немає за визначенням.
## Зони ТІСНІ навмисно. Перша спроба брала їх «з запасом» — і брижі полізли на
## багно та уламки в передньому плані, де вони найпомітніші: виглядало так,
## наче хвилями йде грязюка. Краще недобрати трохи води, ніж набрати суходолу.
PUDDLES = [
    (0.655, 0.688, 0.078, 0.036),  # велика вирва по центру — головна калюжа
    (0.745, 0.673, 0.046, 0.024),  # її права лопать
    (0.515, 0.535, 0.048, 0.022),  # ставок середнього плану
    (0.487, 0.466, 0.046, 0.011),  # мокра смуга вздовж лінії окопів
    (0.800, 0.818, 0.085, 0.032),  # довга калюжа правого низу
    (0.843, 0.877, 0.032, 0.014),  # мала під нею
    (0.380, 0.805, 0.040, 0.030),  # калюжа лівого низу
    (0.535, 0.897, 0.038, 0.016),  # мокрий рукав по центру
    (0.398, 0.945, 0.030, 0.028),  # передній план ліворуч
    (0.640, 0.950, 0.045, 0.028),  # передній план праворуч
    (0.365, 0.680, 0.058, 0.020),  # мокрий поділ ліворуч
    (0.725, 0.610, 0.032, 0.013),  # мокра поличка під бруствером
    (0.445, 0.585, 0.036, 0.015),  # дрібна калюжа лівіше центру
]

## Всередині зони вода все одно не всюди: floor лишає ледь помітні брижі на
## мокрому багні (так воно й виглядає), автооцінка піднімає до 1.0 там, де
## справді вода.
FLOOR = 0.08


def _blur(a: np.ndarray, radius: float) -> np.ndarray:
    img = Image.fromarray((np.clip(a, 0, 1) * 255).astype(np.uint8))
    return np.asarray(img.filter(ImageFilter.GaussianBlur(radius)), np.float32) / 255.0


def main() -> None:
    src = Image.open(SRC).convert("L")
    w, h = src.size[0] // DOWNSCALE, src.size[1] // DOWNSCALE
    g = np.asarray(src.resize((w, h), Image.LANCZOS), np.float32) / 255.0

    # Вода гладка (мало високих частот) і світліша за широке оточення, бо
    # відбиває небо. Багно — навпаки: зернисте й темніше за локальне тло.
    smooth = _blur(g, 2.0)
    detail = _blur(np.clip(np.abs(g - smooth) * 6.0, 0, 1), 4.0)
    local_bg = _blur(g, 24.0)
    brighter = np.clip((smooth - local_bg) * 8.0, 0, 1)
    water = np.clip((brighter * (1.0 - detail) - 0.04) / 0.22, 0, 1)

    # Зони, намальовані руками, з м'яким краєм.
    gate_img = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(gate_img)
    for cx, cy, rx, ry in PUDDLES:
        draw.ellipse(
            [(cx - rx) * w, (cy - ry) * h, (cx + rx) * w, (cy + ry) * h], fill=255)
    gate = _blur(np.asarray(gate_img, np.float32) / 255.0, 6.0)

    mask = gate * np.clip(FLOOR + water * (1.0 - FLOOR), 0, 1)
    mask = _blur(mask, 1.5)

    Image.fromarray((mask * 255).astype(np.uint8)).save(DST)
    print("%s  %dx%d  покриття %.1f%% кадру" % (DST, w, h, 100 * mask.mean()))


if __name__ == "__main__":
    main()
