"""Трубний барражуючий боєприпас: тонкий корпус, розкладені крила, X-оперення, штовхальний гвинт.

Реальний ~1 м; на дошці (тайл = 8 м) це 0,125 тайла, на найдальшому зумі 4 px — не видно.
Тому ×5: довжина 0,62 тайла (5 м), розмах крил 0,56 (4,5 м). Початок координат — середина
корпусу, ніс вздовж +Y Blender (−Z Godot); льотний вузол сам повертає ніс на тангенс траєкторії.

blender -b --factory-startup -P tools/blender/ordnance/drone.py
"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from lib import *

BODY = (0.30, 0.32, 0.27)
WING = (0.62, 0.60, 0.50)
NOSE = (0.12, 0.12, 0.11)
PROP = (0.10, 0.10, 0.10)

b = B()
L = 0.62
# Корпус: тіло-еліпсоїд, довший за товщину в ~9 разів, ніс темніший (головка).
b.ball(BODY, (0, 0, 0), (0.042, L * 0.5, 0.042), 14)
b.ball(NOSE, (0, L * 0.34, 0), (0.036, 0.1, 0.036), 10)
# Крила: тонкі пластини трохи позаду середини, розмах 0,56.
b.box(WING, (0, -0.02, 0.005), (0.56, 0.1, 0.012))
# Хвіст: X-оперення з чотирьох пластин під 45° та штовхальний гвинт.
b.box(WING, (0.07, -L * 0.45, 0.05), (0.14, 0.07, 0.01), 0.0)
b.box(WING, (-0.07, -L * 0.45, 0.05), (0.14, 0.07, 0.01), 0.0)
b.box(WING, (0, -L * 0.45, 0.075), (0.01, 0.07, 0.14), 0.0)
b.box(PROP, (0, -L * 0.5, 0), (0.17, 0.012, 0.014))
b.export("drone")
