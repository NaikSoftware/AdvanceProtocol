"""Трубний барражуючий боєприпас: тонкий корпус, розкладені крила, хвостове оперення, штовхальний гвинт.

Справжні розміри, без збільшення: довжина 1,2 м, діаметр корпусу 0,1 м, розмах крил 0,7 м.
Початок координат — середина корпусу, ніс вздовж +Y Blender (−Z Godot); льотний вузол сам
повертає ніс на тангенс траєкторії. Будуємо в метрах, на виході множимо на 1/8.

blender -b --factory-startup -P tools/blender/ordnance/drone.py
"""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from lib import *

BODY = (0.30, 0.32, 0.27)
WING = (0.62, 0.60, 0.50)
NOSE = (0.12, 0.12, 0.11)
PROP = (0.10, 0.10, 0.10)

b = B()
L = 1.2
b.ball(BODY, (0, 0, 0), (0.05, L * 0.5, 0.05), 14)
b.ball(NOSE, (0, L * 0.34, 0), (0.045, 0.2, 0.045), 10)
b.box(WING, (0, -0.04, 0.01), (0.7, 0.12, 0.012))                 # крила
b.box(WING, (0.1, -L * 0.45, 0.06), (0.2, 0.08, 0.01))            # стабілізатор
b.box(WING, (-0.1, -L * 0.45, 0.06), (0.2, 0.08, 0.01))
b.box(WING, (0, -L * 0.45, 0.09), (0.01, 0.08, 0.16))             # кіль
b.box(PROP, (0, -L * 0.5, 0), (0.22, 0.012, 0.016))               # штовхальний гвинт
b.export("drone", scale=0.125)
