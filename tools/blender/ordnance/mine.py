"""Протитанкова міна на розритому ґрунті: своя (лише міна) і розкрита ворожа (міна + позначка сапера).

Реальна міна ~0,3 м, на дошці (тайл = 8 м) це 0,04 тайла, тобто 3 px на найближчому зумі — не видно.
Тому діаметр 0,34 тайла (2,7 м, збільшення ×9), ґрунтова пляма 0,64 тайла (5 м).
Розкрита ворожа додатково має квадратну огорожу з чотирьох кілків і червоно-білої стрічки
(форма: квадрат проти кола), без жодних національних знаків.

blender -b --factory-startup -P tools/blender/ordnance/mine.py
"""
import sys, os, math, random
sys.path.insert(0, os.path.dirname(__file__))
from lib import *

SOIL = (0.23, 0.165, 0.105)
SOIL_LIGHT = (0.33, 0.25, 0.16)
BODY = (0.22, 0.25, 0.11)
PLATE = (0.47, 0.47, 0.27)
FUSE = (0.84, 0.76, 0.52)
RED = (0.78, 0.09, 0.07)
WHITE = (0.92, 0.9, 0.84)


def mine(b):
    rnd = random.Random(7)
    # Розритий ґрунт: кілька накладених нерівних дисків, свіжий (світліший) насип поверх темного.
    b.cone(SOIL, (0, 0, 0), 0.34, 0.28, 0.025, 14)
    for i in range(5):
        a = i * 1.26 + rnd.random() * 0.4
        d = 0.15 + rnd.random() * 0.06
        b.cone(SOIL_LIGHT if i % 2 else SOIL, (math.cos(a) * d, math.sin(a) * d, 0.0), 0.12 + rnd.random() * 0.05, 0.08, 0.03 + rnd.random() * 0.012, 7, rnd.random())
    # Корпус сидить у ґрунті наполовину; верхня плита й паливо світліші за корпус, щоб читались на брудній землі.
    b.cone(BODY, (0, 0, 0.012), 0.17, 0.165, 0.058, 16)
    b.cone(PLATE, (0, 0, 0.068), 0.15, 0.13, 0.014, 16)
    b.cone(FUSE, (0, 0, 0.081), 0.062, 0.05, 0.02, 12)


def markers(b):
    h, r = 0.24, 0.3
    pts = [(-r, -r), (r, -r), (r, r), (-r, r)]
    for x, y in pts:
        b.box(WHITE, (x, y, h * 0.3), (0.024, 0.024, h * 0.6))
        b.box(RED, (x, y, h * 0.8), (0.026, 0.026, h * 0.4))
    # Стрічка між кілками на висоті ~пів стійки: смугою червоних і білих відрізків.
    for i in range(4):
        (x0, y0), (x1, y1) = pts[i], pts[(i + 1) % 4]
        n = 5
        for k in range(n):
            t0, t1 = k / n, (k + 1) / n
            cx = (x0 + (x1 - x0) * (t0 + t1) / 2); cy = (y0 + (y1 - y0) * (t0 + t1) / 2)
            ln = math.hypot(x1 - x0, y1 - y0) / n
            ang = math.atan2(y1 - y0, x1 - x0)
            b.box(RED if k % 2 == 0 else WHITE, (cx, cy, h * 0.62), (ln, 0.012, 0.04), ang)


b = B(); mine(b); b.export("mine_own")
b = B(); mine(b); markers(b); b.export("mine_enemy")
