"""Протитанкова міна: своя — закопана врівень, видно лише верхній диск у плямі розритого ґрунту;
знайдена ворожа — відкопана, лежить на поверхні всім корпусом біля невеликого відвалу темного ґрунту.

Справжні розміри, без збільшення: міна 0,3 м у діаметрі й 0,1 м заввишки (0,0375 тайла), пляма
ґрунту ~1,6 м (своя) і ~1,0 м (відвал ворожої). Читається вона плямою й рухом камери, не розміром.
Чия міна — не модель, а тонке кільце кольору власника (MineLayer). Без кілків, стрічки й прапорців.
Будуємо в метрах, на виході множимо на 1/8 (тайл = 8 м = 1,0).

blender -b --factory-startup -P tools/blender/ordnance/mine.py
"""
import sys, os, math, random
sys.path.insert(0, os.path.dirname(__file__))
from lib import *

SOIL = (0.23, 0.165, 0.105)
SOIL_LIGHT = (0.33, 0.25, 0.16)
BODY = (0.22, 0.25, 0.11)
PLATE = (0.47, 0.47, 0.27)
FUSE = (0.84, 0.76, 0.52)


def soil(b, r, seed):
    """Розритий ґрунт: накладені нерівні диски, свіжий (світліший) насип поверх темного."""
    rnd = random.Random(seed)
    b.cone(SOIL, (0, 0, 0), r, r * 0.82, 0.05, 14)
    for i in range(5):
        a = i * 1.26 + rnd.random() * 0.4
        d = r * (0.45 + rnd.random() * 0.15)
        b.cone(SOIL_LIGHT if i % 2 else SOIL, (math.cos(a) * d, math.sin(a) * d, 0.0), r * (0.34 + rnd.random() * 0.12), r * 0.24, 0.06 + rnd.random() * 0.025, 7, rnd.random())


F = float(os.environ.get("MINE_FACTOR", "8.0"))   # збільшення міни (лише її, не ґрунту) для читабельності


def device(b, base, exposed):
    """Корпус-диск з верхньою плитою, паливом і ручкою для перенесення; закопана — лише верх."""
    z0 = 0.0 if exposed else 0.055 - 0.07 * F + 0.0
    if exposed:
        b.cone(BODY, (0, 0, 0.03), 0.15 * F, 0.145 * F, 0.07 * F, 16)
        top = 0.03 + 0.07 * F
    else:
        top = 0.055
    b.cone(PLATE, (0, 0, top), 0.13 * F, 0.115 * F, 0.012 * F + 0.01, 16)
    t2 = top + 0.012 * F + 0.01
    b.cone(FUSE, (0, 0, t2), 0.045 * F, 0.035 * F, 0.012 * F, 12)
    # Ручка: планка на двох стійках через верх диска, перпендикулярно до палива.
    b.box(BODY, (0, 0.085 * F, t2 + 0.012 * F), (0.12 * F, 0.016 * F, 0.016 * F))
    b.box(BODY, (0.055 * F, 0.085 * F, t2 + 0.004 * F), (0.014 * F, 0.016 * F, 0.012 * F))
    b.box(BODY, (-0.055 * F, 0.085 * F, t2 + 0.004 * F), (0.014 * F, 0.016 * F, 0.012 * F))


def own(b):
    soil(b, 0.85, 7)
    device(b, 0, False)


def enemy(b):
    soil(b, 0.5, 11)
    device(b, 0, True)


b = B(); own(b); b.export("mine_own", scale=0.125)
b = B(); enemy(b); b.export("mine_enemy", scale=0.125)
